// Bundles src/runtime/entry.ts into a minified IIFE and writes it as a string
// constant to src/generated/runtime.ts, so the React component can inline it.
// Also writes dist/runtime.iife.js for anyone who wants the raw file.
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [join(root, 'src/runtime/entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: '__ctfs',
  target: ['es2017'],
  platform: 'browser',
  write: false,
  legalComments: 'none',
  define: { __VERSION__: JSON.stringify(version) },
})

const code = result.outputFiles[0].text.trim()
mkdirSync(join(root, 'src/generated'), { recursive: true })
writeFileSync(
  join(root, 'src/generated/runtime.ts'),
  `// GENERATED by scripts/build-runtime.mjs — do not edit.\n` +
    `export const RUNTIME_VERSION = ${JSON.stringify(version)}\n` +
    `export const RUNTIME_SOURCE = ${JSON.stringify(code)}\n`,
)
mkdirSync(join(root, 'dist'), { recursive: true })
writeFileSync(join(root, 'dist/runtime.iife.js'), code + '\n')
console.log(`runtime: ${(code.length / 1024).toFixed(1)} KB minified (v${version})`)
